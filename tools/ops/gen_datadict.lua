-- Writes the Spyglass data dictionary (search-helper 16_Registries/16_02_Data_Dictionary.md, STP-00285) from
-- M.PSS_DataDict: one section per index, a row per field with every attribute it has. Not shipped.
--   lua5.1 tools/ops/gen_datadict.lua --stdout            the document on stdout
--   lua5.1 tools/ops/gen_datadict.lua <path>              written to <path>
-- It loads the addon in the harness (the Warehouse on, so every index is declared with its source types).
if M and M.PSS_DataDictRows then
	M.PSS_Need("Libraries")
	local rows = M.PSS_DataDictRows()
	local function show(v)
		if v == nil then return "" end
		if type(v) ~= "table" then return tostring(v) end
		if v.lo ~= nil then return v.lo .. " to " .. v.hi end
		local t = {}
		for i, s in ipairs(v) do t[i] = "`" .. tostring(s) .. "`" end
		return table.concat(t, ", ")
	end
	local function cell(s) return (tostring(s or ""):gsub("|", "\\|"):gsub("\n", " ")) end
	local out = {}
	local function w(s) out[#out + 1] = s end
	w("# 16_02_Data_Dictionary: every index, source type, field and the values it holds (`STP-00285`)")
	w("")
	w("Generated by [`tools/ops/gen_datadict.lua`](https://github.com/racetracks/PourSocialScore/blob/main/tools/ops/gen_datadict.lua) from `M.PSS_DataDict` ([PSS_IxCatalog.lua](https://github.com/racetracks/PourSocialScore/blob/main/PourSocialScore_Libraries/PSS_IxCatalog.lua)); do not edit by hand ([`TST-00964`](https://github.com/racetracks/Pour-Social-Score_Scratch/blob/main/documents/features/search-helper/15_Tests.md#tst-00964) phase `dictgen` compares it byte for byte). A row's kind, doc, pushdown and join come from its index declaration; values, unit and source from the dictionary. Row shape version " .. M.PSS_DATADICT_V .. ".")
	w("")
	w("## Contents")
	local names = M.PSS_IxNames()
	w("- [Kinds](#kinds)")
	for _, n in ipairs(names) do w("- [`" .. n .. "`](#" .. n .. ")") end
	w("- [Virtual fields](#virtual-fields)")
	w("")
	w("## Kinds")
	w("| Kind | Meaning |")
	w("| --- | --- |")
	local kinds = {}
	for k in pairs(M.PSS_IxKinds) do kinds[#kinds + 1] = k end
	table.sort(kinds)
	for _, k in ipairs(kinds) do w("| `" .. k .. "` | " .. cell(M.PSS_IxKinds[k].doc) .. " |") end
	for _, n in ipairs(names) do
		local x = M.PSS_Ix(n)
		w("")
		w("## " .. n)
		w(cell(x.doc) .. ". Kind " .. x.kind .. ", owner `" .. x.owner .. "`, gate " .. (x.gate and ("`" .. x.gate .. "`") or "none") .. ", residency " .. x.residency .. (x.part and (" (needs " .. x.part .. ")") or "") .. ".")
		w("")
		w("| Field | Kind | Values | Unit | P | J | Doc |")
		w("| --- | --- | --- | --- | --- | --- | --- |")
		for _, f in ipairs(x.fields) do
			local r = rows[n .. "." .. f[1]]
			w("| `" .. f[1] .. "` | `" .. r.kind .. "` | " .. cell(show(r.values)) .. " | " .. cell(r.unit) .. " | " .. (r.pushdown and "P" or "") .. " | " .. (r.join and ("`" .. r.join .. "`") or "") .. " | " .. cell(r.doc) .. " |")
		end
	end
	w("")
	w("## Virtual fields")
	w("| Field | On | Resolves to |")
	w("| --- | --- | --- |")
	w("| `realm`, `faction`, `class` | any index with `ent` | an entity id set (pushed down) |")
	w("| `weekday`, `hour` | any event index | computed from `time` when a query names them |")
	w("| `<dict>_<field>` | after `join <dict>` | the dictionary's columns (`item`, `ent`, `owner`, `cmp`, `evt`, `channel`) |")
	w("| `#keyword` | any index with `item` | the `item.search` keyword set |")
	print("BEGIN-DOC")
	io.write(table.concat(out, "\n"), "\n")
	print("END-DOC")
	return
end
local h = io.popen("PSS_COMPONENTS=logging,warehouse,addons,dtt lua5.1 tools/harness/run.lua . - - tools/ops/gen_datadict.lua 2>&1")
local all = h:read("*a")
h:close()
local doc = all:match("BEGIN%-DOC\n(.-)END%-DOC")
if not doc then io.stderr:write("gen_datadict: the harness did not write the document:\n" .. all:sub(1, 600)) os.exit(1) end
if arg[1] == "--stdout" or not arg[1] then io.write(doc) else local fh = assert(io.open(arg[1], "wb")); fh:write(doc); fh:close(); print("wrote " .. arg[1]) end
